import { test, expect } from "@playwright/test";
import { owner, importFixture, request, origin } from "../cloud/helpers.js";
import { applyAction, emptyState } from "../../server/engine.js";

test("group cards select teams for one-way moves and swaps on desktop and mobile", async ({ browser }) => {
  const o = await owner();
  let s = applyAction(emptyState(), "tournament", { name: "Group editor", size: 1, groups: 2, qualify: 2, points: 5, cap: 6, bestOf: 1 });
  const tid = s.tournaments[0].id;
  s = applyAction(s, "teams", { tournamentId: tid, teams: Array.from({ length: 8 }, (_, i) => ({ players: [`Player ${i + 1}`] })) });
  const state = await importFixture(o, applyAction(s, "generate", { tournamentId: tid }));
  const first = state.teams.find(t => t.group === 0);
  const context = await browser.newContext();
  await context.addCookies([{ name: "sh_session", value: o.cookie.slice("sh_session=".length), url: origin, httpOnly: true, secure: true, sameSite: "Strict" }]);
  const page = await context.newPage();
  await page.goto(`${origin}/teams?tournament=${tid}`);
  await page.getByRole("button", { name: "Edit groups", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("combobox")).toHaveCount(0);
  await expect(dialog.getByRole("button", { name: "Confirm move", exact: true })).toBeDisabled();
  await dialog.getByRole("button", { name: `Select ${first.name} in Group A`, exact: true }).click();
  await expect(dialog.getByRole("button", { name: `Select ${first.name} in Group A`, exact: true })).toHaveAttribute("aria-pressed", "true");
  await dialog.getByRole("button", { name: "Move to Group B", exact: true }).click();
  await expect(dialog.locator(".group-swap-preview")).toContainText(`${first.name} moves from Group A to Group B`);
  await page.screenshot({ path: "output/playwright/group-move-desktop.png", fullPage: true });
  await dialog.getByRole("button", { name: "Done", exact: true }).click();
  expect((await request("state", undefined, o.cookie)).data).toEqual(state);
  await page.getByRole("button", { name: `Change group for ${first.name} in Group editor`, exact: true }).click();
  await expect(dialog.getByRole("button", { name: `Select ${first.name} in Group A`, exact: true })).toHaveAttribute("aria-pressed", "true");
  await dialog.getByRole("button", { name: "Move to Group B", exact: true }).click();
  await dialog.getByRole("button", { name: "Confirm move", exact: true }).click();
  await expect(dialog.getByRole("region", { name: "Group A", exact: true })).toContainText("3 teams");
  await expect(dialog.getByRole("region", { name: "Group B", exact: true })).toContainText("5 teams");
  await expect(dialog.getByRole("button", { name: `Select ${first.name} in Group B`, exact: true })).toHaveAttribute("aria-pressed", "false");
  const moved = (await request("state", undefined, o.cookie)).data;
  expect(moved.matches).toHaveLength(13);
  for (const m of state.matches.filter(m => ![m.a, m.b].includes(first.id))) expect(moved.matches.find(x => x.id === m.id)).toEqual(m);

  await page.setViewportSize({ width: 390, height: 844 });
  await dialog.getByRole("button", { name: "Swap teams", exact: true }).click();
  const other = moved.teams.find(t => t.group === 0);
  const teamButton = dialog.getByRole("button", { name: `Select ${other.name} in Group A`, exact: true });
  await teamButton.focus();
  await teamButton.press("Space");
  await expect(teamButton).toHaveAttribute("aria-pressed", "true");
  await dialog.getByRole("button", { name: `Select ${first.name} in Group B`, exact: true }).click();
  await expect(dialog.locator(".group-swap-preview")).toContainText(`${first.name} moves to Group A`);
  await page.screenshot({ path: "output/playwright/group-swap-mobile.png", fullPage: true });
  const size = await dialog.boundingBox();
  expect(size.x).toBeGreaterThanOrEqual(0);
  expect(size.x + size.width).toBeLessThanOrEqual(390);
  await dialog.getByRole("button", { name: "Confirm swap", exact: true }).click();
  await expect(dialog.getByRole("button", { name: `Select ${first.name} in Group A`, exact: true })).toBeVisible();
  const swapped = (await request("state", undefined, o.cookie)).data;
  expect(swapped.teams.find(t => t.id === first.id).group).toBe(0);
  expect(swapped.teams.find(t => t.id === other.id).group).toBe(1);
  expect(swapped.matches.map(({ a, b, ...rest }) => rest)).toEqual(moved.matches.map(({ a, b, ...rest }) => rest));
  await context.close();
});
